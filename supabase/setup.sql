-- C++ Free Functions Review Dashboard
-- Run this in Supabase SQL Editor as the project database owner.
-- IMPORTANT: This creates an allowlist. Only authenticated users whose email is
-- explicitly enabled in dashboard_allowed_users can read or modify review rows.

create table if not exists public.dashboard_allowed_users (
  email text primary key,
  enabled boolean not null default true,
  created_at timestamptz not null default now(),
  constraint dashboard_allowed_users_email_lowercase check (email = lower(email))
);

create table if not exists public.review_functions (
  id bigint generated by default as identity primary key,
  function_name text not null check (char_length(function_name) between 1 and 500),
  scope text not null check (scope in ('Unit spec / Test spec', 'Code Refac')),
  effort_hrs numeric(8,2) not null check (effort_hrs >= 0.5),
  owner text not null,
  reviewer text not null,
  status text not null check (status in ('Not Started', 'In Progress', 'Pushed for Review', 'To Be Checked', 'Review Closed')),
  observations text not null default '' check (char_length(observations) <= 10000),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create or replace function public.set_review_functions_updated_at()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists review_functions_updated_at on public.review_functions;
create trigger review_functions_updated_at
before update on public.review_functions
for each row execute function public.set_review_functions_updated_at();

-- SECURITY DEFINER is narrowly scoped to this boolean check. It does not expose
-- the allowlist rows to clients. The function owner should remain the database owner.
create or replace function public.is_dashboard_user()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1
    from public.dashboard_allowed_users as allowed
    join auth.users as auth_user
      on lower(auth_user.email) = allowed.email
    where auth_user.id = (select auth.uid())
      and allowed.enabled = true
  );
$$;

alter table public.dashboard_allowed_users enable row level security;
alter table public.review_functions enable row level security;

-- Explicitly remove default client grants, then grant only the required CRUD
-- operations on the shared records table to authenticated users.
revoke all on table public.dashboard_allowed_users from anon, authenticated;
revoke all on table public.review_functions from anon, authenticated;
grant select, insert, update, delete on table public.review_functions to authenticated;

revoke all on function public.is_dashboard_user() from public, anon;
grant execute on function public.is_dashboard_user() to authenticated;

-- No anonymous access. Every signed-in request must pass the email allowlist.
drop policy if exists "Allowlisted users can read review functions" on public.review_functions;
drop policy if exists "Allowlisted users can insert review functions" on public.review_functions;
drop policy if exists "Allowlisted users can update review functions" on public.review_functions;
drop policy if exists "Allowlisted users can delete review functions" on public.review_functions;

create policy "Allowlisted users can read review functions"
on public.review_functions for select to authenticated
using ((select public.is_dashboard_user()));

create policy "Allowlisted users can insert review functions"
on public.review_functions for insert to authenticated
with check ((select public.is_dashboard_user()));

create policy "Allowlisted users can update review functions"
on public.review_functions for update to authenticated
using ((select public.is_dashboard_user()))
with check ((select public.is_dashboard_user()));

create policy "Allowlisted users can delete review functions"
on public.review_functions for delete to authenticated
using ((select public.is_dashboard_user()));

-- Keep the identity sequence usable by authenticated inserts.
grant usage, select on sequence public.review_functions_id_seq to authenticated;

-- Initial company records are intentionally NOT included in this repository migration.
-- Keep any approved data import outside the GitHub repository and run it manually
-- in the Supabase SQL Editor only after company approval.

-- Enable Realtime for this table if it is not already in the publication.
do $$
begin
  if not exists (
    select 1
    from pg_publication_tables
    where pubname = 'supabase_realtime'
      and schemaname = 'public'
      and tablename = 'review_functions'
  ) then
    alter publication supabase_realtime add table public.review_functions;
  end if;
exception when undefined_object then
  raise notice 'supabase_realtime publication not found. The app still refreshes every 15 seconds.';
end;
$$;
